'use strict';
// Writes timezone_tables.go from CLDR's windowsZones.xml and timezone.xml.
// Usage: node scripts/gen-timezones.cjs DIR, where DIR holds both files from
// https://github.com/unicode-org/cldr/tree/release-48/common
// (supplemental/windowsZones.xml, bcp47/timezone.xml).
const fs = require('node:fs');
const path = require('node:path');
const dir = process.argv[2];
if (!dir) { console.error('usage: gen-timezones.cjs DIR'); process.exit(2); }
const read = (name) => fs.readFileSync(path.join(dir, name), 'utf8');
const attrs = (tag) => Object.fromEntries([...tag.matchAll(/(\w+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));

// Every alias to the IANA name (the iana attribute when CLDR keeps an older
// name first): Ubuntu's tzdata no longer has the old links.
const canonical = new Map();
for (const [tag] of read('timezone.xml').matchAll(/<type [^>]*>/g)) {
  const a = attrs(tag);
  if (!a.alias || a.deprecated) continue;
  const names = a.alias.split(' ');
  const name = a.iana || names[0];
  if (name === 'Etc/Unknown') continue;
  for (const n of names) if (n !== name) canonical.set(n, name);
}
const canon = (n) => canonical.get(n) || n;

const windows = new Map();
for (const [tag] of read('windowsZones.xml').matchAll(/<mapZone [^>]*>/g)) {
  const a = attrs(tag);
  if (a.territory === '001') windows.set(a.other, canon(a.type.split(' ')[0]));
}
if (windows.size < 100) throw new Error('too few Windows zones: ' + windows.size);

const q = JSON.stringify;
const lines = (m) => [...m].sort(([x], [y]) => (x < y ? -1 : 1)).map(([k, v]) => '\t' + q(k) + ': ' + q(v) + ',\n').join('');
const out = '// Code generated by scripts/gen-timezones.cjs from CLDR 48 windowsZones.xml\n' +
  '// and timezone.xml (Unicode License v3, see THIRD-PARTY-NOTICES.md). DO NOT EDIT.\n\n' +
  'package main\n\n' +
  '// windowsZones maps a Windows time zone key name to its IANA name.\n' +
  'var windowsZones = map[string]string{\n' + lines(windows) + '}\n\n' +
  '// tzAliases maps an older IANA name to the current one.\n' +
  'var tzAliases = map[string]string{\n' + lines(canonical) + '}\n';
const file = path.join(__dirname, '..', 'timezone_tables.go');
fs.writeFileSync(file, out);
require('node:child_process').execFileSync('gofmt', ['-w', file], { stdio: 'inherit' });
