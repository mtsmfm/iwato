'use strict';
// Writes the Link_Term and Link_Bracket data of UTS #58 into web/links.js.
// Usage: node scripts/gen-linkterm.cjs DIR, where DIR holds LinkTerm.txt and
// LinkBracket.txt from https://www.unicode.org/Public/18.0.0/linkification/
const fs = require('node:fs');
const path = require('node:path');
const dir = process.argv[2];
if (!dir) { console.error('usage: gen-linkterm.cjs DIR'); process.exit(2); }
const lines = (name) => fs.readFileSync(path.join(dir, name), 'utf8').split('\n')
  .map((l) => l.replace(/#.*/, '').trim()).filter(Boolean).map((l) => l.split(';').map((f) => f.trim()));

const CLASSES = {Hard: 'H', Include: 'I', Soft: 'S', Open: 'O', Close: 'C'};
const cls = new Uint8Array(0x110000).fill('H'.charCodeAt(0));
for (const [range, value] of lines('LinkTerm.txt')) {
  const [lo, hi = lo] = range.split('..').map((h) => parseInt(h, 16));
  if (!CLASSES[value]) throw new Error('unknown Link_Term ' + value);
  cls.fill(CLASSES[value].charCodeAt(0), lo, hi + 1);
}
// Runs over the whole code space: a class letter, then the length in base 36.
let runs = '', count = 0;
for (let i = 0; i < cls.length;) {
  let j = i + 1;
  while (j < cls.length && cls[j] === cls[i]) j++;
  runs += String.fromCharCode(cls[i]) + (j - i).toString(36);
  count++;
  i = j;
}
// Pairs of Open then Close.
let pairs = '';
for (const [close, open] of lines('LinkBracket.txt')) {
  const c = parseInt(close, 16), o = parseInt(open, 16);
  if (cls[c] !== 67 || cls[o] !== 79) throw new Error('bracket ' + close + ' is not Close/Open');
  pairs += String.fromCodePoint(o, c);
}
const esc = (s) => JSON.stringify(s).replace(/[\u007f-￿]/g, (ch) => '\\u' + ch.charCodeAt(0).toString(16).padStart(4, '0'));
const block = '  // Generated by scripts/gen-linkterm.cjs from Unicode 18.0 LinkTerm.txt and\n' +
  '  // LinkBracket.txt (Unicode License v3, see THIRD-PARTY-NOTICES.md).\n' +
  '  const LINK_TERM_RUNS = ' + esc(runs) + ';\n' +
  '  const LINK_BRACKETS = ' + esc(pairs) + ';\n' +
  '  // End of generated data.\n';
const file = path.join(__dirname, '..', 'web', 'links.js');
const src = fs.readFileSync(file, 'utf8');
const re = /  \/\/ Generated by scripts\/gen-linkterm\.cjs[\s\S]*?  \/\/ End of generated data\.\n/;
if (!re.test(src)) throw new Error('no generated block in ' + file);
fs.writeFileSync(file, src.replace(re, () => block));
console.log(count + ' runs, ' + runs.length + ' characters; ' + pairs.length / 2 + ' bracket pairs');
